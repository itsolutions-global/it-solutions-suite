  function activateFromModal() {
    const firmName = (document.getElementById('wlFirmName')?.value || '').trim();
    const firmCredential = (document.getElementById('wlFirmCred')?.value || '').trim();
    const firmContact = (document.getElementById('wlFirmContact')?.value || '').trim();
    const licenseKey = (document.getElementById('wlLicenseKey')?.value || '').trim().toUpperCase();
    const msgEl = document.getElementById('wlStatusMsg');

    if (!firmName) {
      msgEl.style.display = 'block';
      msgEl.style.color = '#fb7185';
      msgEl.textContent = '⚠ Please enter your Firm or Agency Name.';
      return;
    }

    const res = verifyLicenseKey(licenseKey);
    if (!res.valid) {
      msgEl.style.display = 'block';
      msgEl.style.color = '#fb7185';
      msgEl.textContent = `⚠ ${res.reason}. Use the Order panel below to request your firm's key.`;
      return;
    }

    saveConfig({
      active: true,
      firmName,
      firmCredential,
      firmContact,
      licenseKey,
      tier: res.tier,
      firmCode: res.firmCode,
      activatedAt: new Date().toISOString()
    });

    msgEl.style.display = 'block';
    msgEl.style.color = '#34d399';
    msgEl.textContent = `✔ White-Label License Verified (${res.tier} • ${res.firmCode})! All exports now carry ${firmName} branding.`;
    updateBannerBadges();
  }

