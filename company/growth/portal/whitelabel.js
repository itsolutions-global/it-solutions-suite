    if (!buyerEmail || !buyerEmail.includes('@')) {
      alert('Please enter a valid work email address so we can deliver your activation key and invoice.');
      return;
    }

    const orderData = {
      firmName,
      buyerEmail,
      packageCode,
      packageTitle,
      amountUSD: Number(amountStr || 49),
      product: document.title.split('|')[0].trim()
    };

    const orderId = await submitCommercialOrder(orderData);
    const html = generateProFormaInvoiceHTML(orderId, orderData);
    const blob = new Blob([html], { type: 'text/html' });
    const url = URL.createObjectURL(blob);
