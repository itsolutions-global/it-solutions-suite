  // Deterministic verification salt for offline key validation (paired with CLI generator)
  const VERIFY_PRIME_A = 0x811c9dc5;
  const VERIFY_PRIME_B = 0x01000193;
  const MASTER_NAMESPACE = 'ITSG::WHITELABEL::2026::ENTERPRISE::v1';

  function computeSignature(firmCode, tierCode) {
    const raw = `${MASTER_NAMESPACE}|${firmCode.toUpperCase().trim()}|${tierCode.toUpperCase().trim()}`;
    let h1 = VERIFY_PRIME_A >>> 0;
    let h2 = 0x9e3779b9 >>> 0;
    for (let i = 0; i < raw.length; i++) {
      const c = raw.charCodeAt(i);
      h1 ^= c;
      h1 = Math.imul(h1, VERIFY_PRIME_B) >>> 0;
      h2 = (Math.imul(h2 ^ c, 0x85ebca6b) + 0xc2b2ae35) >>> 0;
    }
    const hex1 = (h1 >>> 0).toString(16).toUpperCase().padStart(8, '0');
    const hex2 = (h2 >>> 0).toString(16).toUpperCase().padStart(8, '0');
    return `${hex1.slice(0, 4)}${hex2.slice(0, 4)}`;
  }

  /**
   * Validates an offline White-Label License Key.
   * Format: ITSG-WL-<TIER>-<FIRMCODE>-<8CHAR_SIG>
   * Example: ITSG-WL-PRO-ACME-94E88B2E
   */
  function verifyLicenseKey(keyStr) {
    if (!keyStr || typeof keyStr !== 'string') return { valid: false, reason: 'Empty license key' };
    const clean = keyStr.trim().toUpperCase();
    const parts = clean.split('-');
    if (parts.length !== 5 || parts[0] !== 'ITSG' || parts[1] !== 'WL') {
      return { valid: false, reason: 'Invalid format. Expected: ITSG-WL-PRO-<FIRMCODE>-<SIGNATURE>' };
    }
    const tier = parts[2];
    const firmCode = parts[3];
    const providedSig = parts[4];

    if (!['PRO', 'AGENCY', 'FIRM', 'ENT'].includes(tier)) {
      return { valid: false, reason: 'Unrecognized license tier code' };
    }
    if (firmCode.length < 2 || firmCode.length > 16) {
      return { valid: false, reason: 'Invalid firm identifier length' };
    }

    const expectedSig = computeSignature(firmCode, tier);
    if (providedSig !== expectedSig) {
      return { valid: false, reason: 'Cryptographic signature mismatch' };
    }

    return {
      valid: true,
      tier: tier,
      firmCode: firmCode,
      signature: providedSig
    };
  }

  function getConfig() {
    try {
      const raw = localStorage.getItem(STORAGE_KEY);
      if (!raw) return null;
      const cfg = JSON.parse(raw);
      if (cfg && cfg.licenseKey && verifyLicenseKey(cfg.licenseKey).valid) {
        return cfg;
      }
    } catch (e) {}
    return null;
  }

  function saveConfig(cfg) {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(cfg));
  }

  function clearConfig() {
    localStorage.removeItem(STORAGE_KEY);
  }

  /**
   * Returns the dynamic attribution footer for exports.
   * If White-Label is active, uses the firm's custom branding.
   * Otherwise returns the clean IT Solutions Global visible attribution.
   */
  function getAttribution(toolName, deliverableType) {
    const docType = deliverableType || 'Audit';
    const cfg = getConfig();
    if (cfg && cfg.active && cfg.firmName) {
      const cred = cfg.firmCredential ? ` (${cfg.firmCredential})` : '';
      const contact = cfg.firmContact ? ` • ${cfg.firmContact}` : '';
      return `*${docType} prepared by ${cfg.firmName}${cred}${contact} — Verified Client-Side Confidential Deliverable*`;
    }
    return `*${docType} generated by ${toolName} — IT Solutions Global (100% Client-Side Local Verification • Zero Cloud Uploads)*`;
  }

  /**
   * Dispatches a B2B commercial order intent or white-label purchase request to /api/feedback
   * and generates a downloadable Pro-Forma Invoice.
   */
  async function submitCommercialOrder(orderData) {
    const orderId = 'ORD-' + Date.now().toString(36).toUpperCase() + '-' + Math.random().toString(36).substring(2, 6).toUpperCase();
    const payload = {
      type: 'commercial_order_intent',
      tool: orderData.product || 'B2B_Solutions_Desk',
      sentiment: 'positive',
      category: `ORDER:${orderData.packageCode || 'WHITELABEL_49'}`,
      comment: JSON.stringify({
        orderId: orderId,
        firmName: orderData.firmName,
        buyerEmail: orderData.buyerEmail,
        packageTitle: orderData.packageTitle,
        amountUSD: orderData.amountUSD,
        notes: orderData.notes || ''
      }),
      url: window.location.href,
      timestamp: new Date().toISOString()
    };

    try {
      const orders = JSON.parse(localStorage.getItem(ORDER_LOG_KEY) || '[]');
      orders.push({ orderId, ...orderData, timestamp: payload.timestamp });
      localStorage.setItem(ORDER_LOG_KEY, JSON.stringify(orders.slice(-50)));
    } catch (e) {}

    try {
      await fetch('/api/feedback', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload)
      });
    } catch (e) {}

    return orderId;
  }

